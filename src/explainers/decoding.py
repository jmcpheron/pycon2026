@dataclass(frozen=True)
class ToothFingerprint:
    z: float                # slice height in mm
    count: int              # detected tooth count (FFT-dominant frequency)
    r_outer: float          # max radial distance in the slice (mm)
    r_inner: float          # min radial distance — useful as sanity check
    derived_module: float   # m = 2·r_outer / (N + 2), in mm
    theta_grid: np.ndarray  # angular samples, shape (720,)
    r_grid: np.ndarray      # radial signal at each theta, shape (720,)
    fft_magnitudes: np.ndarray  # |FFT(r - mean)|, shape (361,)


# ---------------------------------------------------------------------------
# Geometry analysis
# ---------------------------------------------------------------------------

def _slice_r_grid(mesh, z: float, samples: int = 720) -> np.ndarray:
    """Slice ``mesh`` at height ``z`` and return radial-distance-vs-angle.

    Uses trimesh's low-level ``mesh_plane`` (returns ``(N, 2, 3)`` line
    segments) rather than ``mesh.section()`` so we don't need the
    networkx dependency that Path2D pulls in.
    """
    from trimesh.intersections import mesh_plane

    segs = mesh_plane(mesh, plane_normal=[0, 0, 1], plane_origin=[0, 0, z])
    if segs is None or len(segs) == 0:
        raise RuntimeError(f"empty mesh slice at z={z}")

    pts = segs.reshape(-1, 3)
    r = np.hypot(pts[:, 0], pts[:, 1])
    theta = np.arctan2(pts[:, 1], pts[:, 0])

    # Bucket each θ into one of ``samples`` slots and keep the max r in
    # each bucket. A gear cross-section may contain inner features (hub
    # hole, post hole); the outer boundary always has the largest r.
    bucket_size = 2 * np.pi / samples
    bucket_idx = ((theta + np.pi) / bucket_size).astype(int).clip(0, samples - 1)
    r_grid = np.zeros(samples)
    np.maximum.at(r_grid, bucket_idx, r)

    # Fill any empty buckets by interpolation from neighbors.
    mask = r_grid > 0
    if mask.sum() < samples:
        idx = np.arange(samples)
        r_grid = np.interp(idx, idx[mask], r_grid[mask])
    return r_grid


def _tooth_count_via_fft(r_grid: np.ndarray) -> tuple[int, np.ndarray]:
    """Return the dominant angular frequency of r_grid plus the full spectrum.

    A periodic tooth profile produces a strong peak at frequency N (the
    tooth count). DC is bin 0; ignore it. We search up to Nyquist.
    """
    n = len(r_grid)
    signal = r_grid - r_grid.mean()
    spectrum = np.abs(np.fft.rfft(signal))
    # Ignore DC bin; the largest remaining bin index is the tooth count.
    peak_bin = int(np.argmax(spectrum[1:])) + 1
    return peak_bin, spectrum


def _detect(mesh, z: float) -> ToothFingerprint:
    samples = 720
    theta_grid = np.linspace(-np.pi, np.pi, samples, endpoint=False)
    r_grid = _slice_r_grid(mesh, z, samples=samples)
    count, spectrum = _tooth_count_via_fft(r_grid)
    r_outer = float(r_grid.max())
    return ToothFingerprint(
        z=z,
        count=count,
        r_outer=r_outer,
        r_inner=float(r_grid.min()),
        derived_module=2 * r_outer / (count + 2),
        theta_grid=theta_grid,
        r_grid=r_grid,
        fft_magnitudes=spectrum,
    )


