"""Explainer #5 — decoding the gear card from STEP geometry.

Onshape's STEP export drops parametric metadata (gear ratios, tooth counts,
module). All we get is named B-rep solids. This explainer demonstrates
*recovering* the lost design intent from the bytes:

    1. Slice the committed STL of one gear at two z heights.
    2. For each slice, sample the radial profile r(θ) and FFT it.
    3. The dominant non-DC frequency is the tooth count.
    4. The outer radius + tooth count gives the module via
       ``m = 2·r_outer / (N + 2)``.
    5. Compare derived numbers to the canonical values in ``card.py``.

Then a "rolling measuring tape" thought experiment uses the *derived* ratio
to ask: if you rolled the card on edge like a coin, how does the output
gear behave?

Everything is regenerated by CI on every push that touches the STL or this
file, so the page is always honest about what the bytes actually contain.
"""

