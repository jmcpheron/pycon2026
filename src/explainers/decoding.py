def _section_outlines_svg(
    out: Path, disc: ToothFingerprint, pinion: ToothFingerprint,
) -> Path:
    """Side-by-side drawsvg view of the two cross-sections.

    Both at the same px-per-mm scale so the size difference between the
    25.2 mm disc and the 7.2 mm pinion is honest. Panel width is set
    wide enough to fit the longest caption line at FONT_SIZE_DIM.
    """
    px_per_mm = 5.5
    pad = 28.0
    label_h = 54.0  # room for two label lines + breathing
    # Panel width: max of (disc gear + 2mm padding) and minimum for labels.
    gear_w = 2 * (disc.r_outer + 2) * px_per_mm
    panel_w = max(gear_w, 240.0)
    panel_h = gear_w
    gap = pad
    width = 2 * pad + 2 * panel_w + gap
    height = pad + panel_h + label_h + pad

    d = diagrams.new_drawing(width, height)

    def draw_panel(panel_x: float, fp: ToothFingerprint, title: str,
                   fill: str) -> None:
        cx = panel_x + panel_w / 2
        cy = pad + panel_h / 2
        # Boundary as a polygon: convert (θ, r) to (x, y) in px.
        pts: list[float] = []
        for theta, r in zip(fp.theta_grid, fp.r_grid):
            x = cx + r * math.cos(theta) * px_per_mm
            y = cy - r * math.sin(theta) * px_per_mm
            pts.extend([x, y])
        d.append(dw.Lines(*pts, close=True,
                          fill=fill, stroke=S.INK,
                          stroke_width=S.STROKE_NORMAL))
        # Reference circle at outer radius for scale
        d.append(dw.Circle(cx, cy, fp.r_outer * px_per_mm,
                           fill="none", stroke=S.INK_MUTED,
                           stroke_width=S.STROKE_DIM, stroke_dasharray="2 3"))
        # Origin cross-hairs
        d.append(dw.Line(cx - 6, cy, cx + 6, cy,
                         stroke=S.INK_MUTED, stroke_width=S.STROKE_DIM))
        d.append(dw.Line(cx, cy - 6, cx, cy + 6,
                         stroke=S.INK_MUTED, stroke_width=S.STROKE_DIM))
        # Two-line caption: title on top, derived metrics below.
        d.append(dw.Text(title, S.FONT_SIZE_LABEL,
                         x=cx, y=pad + panel_h + 18,
                         text_anchor="middle",
                         font_family=S.FONT_FAMILY,
                         fill=S.INK, font_weight="bold"))
        d.append(dw.Text(
            f"{fp.count} teeth · ⌀ outer {fp.r_outer * 2:.2f} mm · "
            f"module {fp.derived_module:.3f} mm",
            S.FONT_SIZE_DIM,
            x=cx, y=pad + panel_h + 36,
            text_anchor="middle",
            font_family=S.FONT_FAMILY, fill=S.INK_MUTED))

    draw_panel(pad, disc, f"Big disc — slice at z = {disc.z:.2f} mm",
               S.GEAR_BIG)
    draw_panel(pad + panel_w + gap, pinion,
               f"Pinion — slice at z = {pinion.z:.2f} mm",
               S.GEAR_PINION)
    d.save_svg(str(out))
    return out


def _polar_signal_svg(
    out: Path, disc: ToothFingerprint, pinion: ToothFingerprint,
) -> Path:
    """Cartesian r(θ) plot for both gears, with tooth count annotated."""
    fig, (ax_disc, ax_pin) = plt.subplots(2, 1, figsize=(6.5, 4.4), sharex=True)

    for ax, fp, color, title in (
        (ax_disc, disc, S.GEAR_BIG, f"Big disc — r(θ) has {disc.count} peaks"),
        (ax_pin, pinion, S.GEAR_PINION,
         f"Pinion — r(θ) has {pinion.count} peaks"),
    ):
        theta_deg = np.degrees(fp.theta_grid)
        ax.plot(theta_deg, fp.r_grid, color=color, linewidth=1.0)
        ax.axhline(fp.r_grid.mean(), color=S.INK_MUTED,
                   linestyle="--", linewidth=0.5)
        ax.set_ylabel("r (mm)", fontsize=9)
        ax.set_title(title, fontsize=10)
        ax.grid(color=S.LEVEL_LINE, linestyle="--", linewidth=0.4)
        ax.set_axisbelow(True)

    ax_pin.set_xlabel("θ (degrees around the gear axis)", fontsize=9)
    ax_pin.set_xticks(np.arange(-180, 181, 45))
    fig.tight_layout()
    fig.savefig(out, format="svg", bbox_inches="tight",
                metadata={"Date": None})
    plt.close(fig)
    return out


def _fft_svg(
    out: Path, disc: ToothFingerprint, pinion: ToothFingerprint,
) -> Path:
    """Stem plot of FFT magnitudes; the dominant bin = tooth count."""
    fig, axes = plt.subplots(1, 2, figsize=(7.0, 3.2))

    for ax, fp, color, title in (
        (axes[0], disc, S.GEAR_BIG, "Big disc"),
        (axes[1], pinion, S.GEAR_PINION, "Pinion"),
    ):
        # Drop DC; clip to show the interesting low end.
        spectrum = fp.fft_magnitudes
        max_bin = min(fp.count * 3 + 5, len(spectrum) - 1)
        bins = np.arange(1, max_bin + 1)
        mags = spectrum[1:max_bin + 1]
        markerlines = ax.stem(bins, mags, basefmt=" ")
        plt.setp(markerlines.markerline, color=color, markersize=4)
        plt.setp(markerlines.stemlines, color=color, linewidth=0.8)
        # Highlight the winning bin
        ax.axvline(fp.count, color=S.ACCENT_HILITE, linestyle="--",
                   linewidth=0.8, alpha=0.7)
        ax.annotate(f"N = {fp.count}",
                    xy=(fp.count, mags.max()),
                    xytext=(8, -2), textcoords="offset points",
                    fontsize=10, color=S.ACCENT_HILITE, fontweight="bold")
        ax.set_xlabel("angular frequency (cycles per revolution)", fontsize=8)
        ax.set_ylabel("|FFT(r − mean)|", fontsize=8)
        ax.set_title(title, fontsize=10)
        ax.grid(color=S.LEVEL_LINE, linestyle="--", linewidth=0.4)
        ax.set_axisbelow(True)

    fig.tight_layout()
    fig.savefig(out, format="svg", bbox_inches="tight",
                metadata={"Date": None})
    plt.close(fig)
    return out


def _comparison_svg(
    out: Path, disc: ToothFingerprint, pinion: ToothFingerprint,
) -> Path:
    """Bar chart: canonical (card.py) vs derived (from STL) for 5 params."""
    derived_ratio_per_stage = disc.count / pinion.count
    derived_total_ratio = derived_ratio_per_stage ** (card.N_STAGES - 1)

    labels = [
        "big teeth", "pinion teeth", "module (mm)",
        "ratio/stage", "total ratio",
    ]
    canonical = [
        card.BIG_TEETH, card.PINION_TEETH, card.MODULE_MM,
        card.RATIO_PER_STAGE, card.TOTAL_RATIO,
    ]
    derived = [
        disc.count, pinion.count, disc.derived_module,
        derived_ratio_per_stage, derived_total_ratio,
    ]

    x = np.arange(len(labels))
    width = 0.36

    fig, ax = plt.subplots(figsize=(7.0, 3.4))
    ax.bar(x - width / 2, canonical, width,
           color=S.GEAR_BIG, edgecolor=S.INK, linewidth=0.5,
           label="canonical (card.py)")
    ax.bar(x + width / 2, derived, width,
           color=S.ACCENT_HILITE, edgecolor=S.INK, linewidth=0.5,
           label="derived (from STL)")
    ax.set_yscale("log")
    ax.set_xticks(x)
    ax.set_xticklabels(labels, fontsize=9)
    ax.set_ylabel("value (log)", fontsize=9)
    ax.set_title("Canonical design vs. geometry-derived values",
                 fontsize=11)
    ax.legend(fontsize=8, loc="upper left")
    ax.grid(axis="y", which="both", color=S.LEVEL_LINE,
            linestyle="--", linewidth=0.4)
    ax.set_axisbelow(True)
    for xi, (c, dv) in enumerate(zip(canonical, derived)):
        for offset, val in ((-width / 2, c), (width / 2, dv)):
            label = f"{val:.3g}" if val < 1000 else f"{val:.0f}"
            ax.text(xi + offset, val, label,
                    ha="center", va="bottom", fontsize=7, color=S.INK)
    fig.tight_layout()
    fig.savefig(out, format="svg", bbox_inches="tight",
                metadata={"Date": None})
    plt.close(fig)
    return out


def _rolling_tape_svg(out: Path, disc: ToothFingerprint,
                      derived_total_ratio: float) -> Path:
    """A 1-metre measuring tape with input/output gear position markers."""
    width_mm = 1000.0  # we map 1 m of tape to the page
    px_per_mm = 0.62   # → ~620 px tape
    tape_h = 26.0
    pad = 50.0
    label_h = 90.0
    width = 2 * pad + width_mm * px_per_mm
    height = pad + label_h + tape_h + 90 + pad

    d = diagrams.new_drawing(width, height)

    tape_x = pad
    tape_y = pad + label_h
    tape_w = width_mm * px_per_mm

    # Header text
    d.append(dw.Text(
        "Roll the card on edge like a coin — the input gear contacts the floor.",
        S.FONT_SIZE_LABEL, x=width / 2, y=pad + 12,
        text_anchor="middle", font_family=S.FONT_FAMILY,
        fill=S.INK, font_weight="bold"))
    d.append(dw.Text(
        f"Input OD = {disc.r_outer * 2:.2f} mm  ·  "
        f"circumference = {math.pi * disc.r_outer * 2:.1f} mm  ·  "
        f"chain ratio = {int(derived_total_ratio):,}:1",
        S.FONT_SIZE_DIM, x=width / 2, y=pad + 30,
        text_anchor="middle", font_family=S.FONT_FAMILY,
        fill=S.INK_MUTED))

    # Tape body
    d.append(dw.Rectangle(tape_x, tape_y, tape_w, tape_h,
                          fill="#fde68a", stroke=S.INK,
                          stroke_width=S.STROKE_NORMAL))
    # Tick marks every 100 mm, labels every 100 mm
    for mm in range(0, 1001, 50):
        x = tape_x + mm * px_per_mm
        h = 10 if mm % 100 == 0 else 5
        d.append(dw.Line(x, tape_y, x, tape_y + h,
                         stroke=S.INK, stroke_width=S.STROKE_THIN))
        if mm % 200 == 0:
            d.append(dw.Text(f"{mm / 1000:g} m", S.FONT_SIZE_DIM,
                             x=x, y=tape_y + tape_h + 14,
                             text_anchor="middle",
                             font_family=S.FONT_FAMILY, fill=S.INK))

    # Input rotations marker — happens often; show every 5th rotation as a tick
    circumference_mm = math.pi * disc.r_outer * 2
    n_input_rot = width_mm / circumference_mm
    label_y = tape_y - 12
    d.append(dw.Text(f"input gear: {n_input_rot:.1f} rotations over 1 m",
                     S.FONT_SIZE_DIM, x=tape_x, y=label_y,
                     font_family=S.FONT_FAMILY, fill=S.INK_MUTED))

    # Output progress as a thin overlay bar on the tape
    output_rot = n_input_rot / derived_total_ratio
    output_deg = output_rot * 360
    output_frac = output_rot  # one full output rotation maps to all of tape
    # Display "what fraction of an output rotation has happened" as a wedge.
    wedge_cx = pad + tape_w + 28
    wedge_cy = tape_y + tape_h / 2
    if wedge_cx + 38 > width:
        wedge_cx = width - 42  # safety, shouldn't trigger
    d.append(dw.Circle(wedge_cx, wedge_cy, 32,
                       fill=S.PAPER, stroke=S.INK,
                       stroke_width=S.STROKE_NORMAL))
    # Sector of `output_deg` degrees, starting at 12 o'clock (−90° in SVG).
    rad_a = -math.pi / 2
    rad_b = rad_a + math.radians(output_deg)
    arc_x0 = wedge_cx + 32 * math.cos(rad_a)
    arc_y0 = wedge_cy + 32 * math.sin(rad_a)
    arc_x1 = wedge_cx + 32 * math.cos(rad_b)
    arc_y1 = wedge_cy + 32 * math.sin(rad_b)
    large_arc = 1 if output_deg > 180 else 0
    path = dw.Path(fill=S.ACCENT_HILITE, fill_opacity=0.45,
                   stroke=S.INK, stroke_width=S.STROKE_THIN)
    path.M(wedge_cx, wedge_cy).L(arc_x0, arc_y0)
    path.A(32, 32, 0, large_arc, 1, arc_x1, arc_y1)
    path.L(wedge_cx, wedge_cy).Z()
    d.append(path)

    # Tape footer text
    footer_y = tape_y + tape_h + 38
    d.append(dw.Text(
        f"output gear after rolling 1 m: {output_rot:.4f} rotations "
        f"≈ {output_deg:.1f}°",
        S.FONT_SIZE_LABEL,
        x=width / 2, y=footer_y,
        text_anchor="middle", font_family=S.FONT_FAMILY,
        fill=S.ACCENT_HILITE, font_weight="bold"))
    d.append(dw.Text(
        f"To get one full output rotation you'd have to roll "
        f"{(1.0 / output_rot):.1f} metres.",
        S.FONT_SIZE_DIM, x=width / 2, y=footer_y + 18,
        text_anchor="middle", font_family=S.FONT_FAMILY, fill=S.INK_MUTED))

    d.save_svg(str(out))
    return out


def _rolling_scale_svg(out: Path, disc: ToothFingerprint,
                       derived_total_ratio: float) -> Path:
    """A horizontal scale comparison: how far for ONE output rotation."""
    circumference_mm = math.pi * disc.r_outer * 2
    roll_for_one_output_m = derived_total_ratio * circumference_mm / 1000

    # Familiar landmarks for scale (metres)
    landmarks = [
        ("PyCon booth (3 m)", 3.0, S.INK_MUTED),
        ("badminton court (13.4 m)", 13.4, S.INK_MUTED),
        (f"one output click ({roll_for_one_output_m:.1f} m)",
         roll_for_one_output_m, S.ACCENT_HILITE),
        ("Olympic pool (50 m)", 50.0, S.INK_MUTED),
    ]
    max_m = max(m for _, m, _ in landmarks) * 1.05

    width = 880.0
    pad_l = 60.0
    pad_r = 200.0  # generous right margin so "Olympic pool (50 m)" never clips
    row_h = 30.0
    height = 70 + len(landmarks) * row_h + 40
    d = diagrams.new_drawing(width, height)

    d.append(dw.Text(
        "How far do you have to roll the card for the output gear to click once?",
        S.FONT_SIZE_LABEL, x=width / 2, y=24,
        text_anchor="middle", font_family=S.FONT_FAMILY,
        fill=S.INK, font_weight="bold"))

    bar_x = pad_l
    bar_w = width - pad_l - pad_r
    pad = 50.0  # used below for the x-axis label spacing

    for i, (label, m, color) in enumerate(landmarks):
        y = pad + i * row_h
        # Label on the right of the bar
        bar_len = (m / max_m) * bar_w
        d.append(dw.Rectangle(bar_x, y, bar_len, row_h - 8,
                              fill=color, fill_opacity=0.7,
                              stroke=S.INK, stroke_width=S.STROKE_THIN))
        d.append(dw.Text(
            label, S.FONT_SIZE_DIM,
            x=bar_x + bar_len + 6, y=y + (row_h - 8) / 2 + 3,
            font_family=S.FONT_FAMILY,
            fill=color, font_weight="bold" if "output" in label else "normal"))

    # x-axis tick marks
    axis_y = pad + len(landmarks) * row_h + 4
    d.append(dw.Line(bar_x, axis_y, bar_x + bar_w, axis_y,
                     stroke=S.INK, stroke_width=S.STROKE_THIN))
    for m in (0, 10, 20, 30, 40, 50):
        if m > max_m:
            break
        x = bar_x + (m / max_m) * bar_w
        d.append(dw.Line(x, axis_y, x, axis_y + 4,
                         stroke=S.INK, stroke_width=S.STROKE_THIN))
        d.append(dw.Text(f"{m} m", S.FONT_SIZE_DIM,
                         x=x, y=axis_y + 16,
                         text_anchor="middle",
                         font_family=S.FONT_FAMILY, fill=S.INK_MUTED))

    d.save_svg(str(out))
    return out


